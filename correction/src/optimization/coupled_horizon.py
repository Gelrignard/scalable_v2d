"""Joint observation fitting, robot trajectory, contact and force optimization.

This replaces the *architecture* of pose repair followed by force allocation.
The old experiments remain available for comparison. A numerical solution is
not an execution certificate: dense geometry audits and physics replay gate
export. Only fixed-mode, non-impact, box-object phases are supported initially.
"""
from dataclasses import asdict, dataclass
from time import perf_counter

import casadi as ca
import numpy as np
from scipy.interpolate import BSpline, CubicHermiteSpline, CubicSpline
from scipy.spatial.transform import Rotation, Slerp, RotationSpline

from correction.src.dynamics.symbolic_mechanics import (
    orientation_error, quat_mul, quat_rotation, rotation_quat)


@dataclass
class HorizonSettings:
    max_iterations: int = 600
    max_seconds: float = 120.
    tolerance: float = 2e-6
    torque_margin: float = .85
    posture_sigma: float = .35
    posture_weight: float = .025
    acceleration_weight: float = .05
    jerk_weight: float = .05
    force_weight: float = .03
    force_rate_weight: float = .03
    torque_weight: float = .03
    data_allowance: float = .08
    lexicographic: bool = True
    print_level: int = 0
    exact_hessian: bool = True
    data_stage_regularizer: float = .001
    # Optional contact-torque-to-position contract; default retains the old NLP.
    servo_kp: tuple | None = None
    servo_max_offset: float | tuple = .1
    servo_offset_rate: float = .5


def robust(z, delta=2.):
    """Smooth pseudo-Huber loss on normalized residuals, component by component."""
    return ca.sum1(ca.vec(2*delta**2*(ca.sqrt(1+(z/delta)**2)-1)))


def hermite(p0, p1, v0, v1, h, u):
    return ((2*u**3-3*u**2+1)*p0+(-2*u**3+3*u**2)*p1
            +(u**3-2*u**2+u)*h*v0+(u**3-u**2)*h*v1)


def solve_horizon(reference, robot, settings=None, *, collision_cuts=(), warm_start=None):
    """Solve one complete contact phase; all times and world coordinates persist.

    Collision cuts are geometric witnesses generated by an external full-mesh
    audit, not penetration penalties hidden in the objective.
    """
    started = perf_counter()
    ref = reference.validate(robot)
    cfg = settings or HorizonSettings()
    if not 0 < cfg.torque_margin <= 1 or cfg.data_allowance < 0:
        raise ValueError('Invalid torque margin or data allowance')
    n, nc, nr = len(ref.times), len(ref.contacts), robot.count
    servo_kp = servo_bound = None
    if cfg.servo_kp is not None:
        servo_kp = np.broadcast_to(np.asarray(cfg.servo_kp, float), (robot.n,))
        servo_bound = np.broadcast_to(np.asarray(cfg.servo_max_offset, float), (robot.n,))
        if (not np.isfinite(servo_kp).all() or np.any(servo_kp <= 0)
                or not np.isfinite(servo_bound).all() or np.any(servo_bound <= 0)
                or not np.isfinite(cfg.servo_offset_rate) or cfg.servo_offset_rate <= 0):
            raise ValueError('Invalid optional servo contract')
    duration = ref.times[-1]-ref.times[0]
    opt = ca.Opti()
    # Eliminate redundant collocation states for the robot. This is the same
    # C2 piecewise-cubic trajectory space, represented by local spline controls.
    spline_knots = np.r_[np.repeat(ref.times[0], 4), ref.times[1:-1], np.repeat(ref.times[-1], 4)]
    basis = BSpline(spline_knots, np.eye(n+2), 3)
    coefficients = opt.variable(robot.n, n+2)
    q, v, a = [coefficients@ca.DM(basis(ref.times, derivative).T) for derivative in range(3)]
    x, vel, momentum = [opt.variable(3, n) for _ in range(3)]
    quat = opt.variable(4, n)
    force = opt.variable(3*nc, n)
    anchors, anchor_terms, uv = [], [], []
    for patch in ref.contacts:
        if patch.radius:
            u = opt.variable(2)
            opt.subject_to(opt.bounded(-patch.radius, u, patch.radius))
            anchors.append(ca.DM(patch.center)+ca.DM(patch.tangents)@u)
            opt.set_initial(u, 0)
            uv.append(u)
        else:
            anchors.append(ca.DM(patch.center)); uv.append(None)
        if patch.robot_index >= 0:
            observed = patch.center if patch.observed_center is None else patch.observed_center
            anchor_terms.append(ca.sumsqr((anchors[-1]-observed)/patch.sigma))
    for variable, lo, hi in ((q, robot.lower, robot.upper), (v, -robot.speed, robot.speed),
                             (a, -robot.acceleration, robot.acceleration)):
        opt.subject_to(opt.bounded(ca.repmat(ca.DM(lo), 1, n), variable, ca.repmat(ca.DM(hi), 1, n)))
    opt.subject_to(q[:, 0] == ref.initial_q)
    opt.subject_to(v[:, 0] == ref.initial_joint_velocity)
    opt.subject_to(x[:, 0] == ref.initial_position)
    opt.subject_to(quat[:, 0] == ref.initial_wxyz)
    opt.subject_to(vel[:, 0] == ref.initial_velocity)
    opt.subject_to(momentum[:, 0] == ref.initial_angular_momentum)
    opt.subject_to(ca.sumsqr((x[:, -1]-ref.goal_position)/ref.goal_position_tolerance) <= 1)
    opt.subject_to(ca.sumsqr(orientation_error(ref.goal_wxyz, quat[:, -1])/ref.goal_rotation_tolerance) <= 1)
    if ref.goal_rest:
        opt.subject_to(vel[:, -1] == 0)
        opt.subject_to(momentum[:, -1] == 0)
        opt.subject_to(v[:, -1] == 0)
    rotation = [quat_rotation(quat[:, k]) for k in range(n)]
    acceleration, moments, omega, torque, hand_points, hand_force = [], [], [], [], [], []
    servo_offsets = []
    reg = 0
    corners = np.array([[sx, sy, sz] for sx in (-1, 1) for sy in (-1, 1) for sz in (-1, 1)])*ref.half_size
    support_heights = sorted(set(p.support_z for p in ref.contacts if p.support_z is not None))
    # A world-horizontal support plane is currently the only environment model.
    if len(support_heights) > 1:
        raise ValueError('Multiple support planes need explicit finite support geometry')
    if any(p.support_z is not None and p.active.any() and not p.active[0] for p in ref.contacts):
        raise ValueError('Initial support only; later touchdown needs a separate contact-mode model')
    for k in range(n):
        rm = rotation[k]
        supported = any(p.support_z is not None and p.active[k] for p in ref.contacts)
        inward = np.zeros((3, nr))
        for patch in ref.contacts:
            if patch.robot_index >= 0:
                inward[:, patch.robot_index] = patch.inward
        tips = robot.contact_positions(q[:, k], ref.base[k], rm, ca.DM(inward))
        hand_points.append(tips)
        world_hand = [ca.MX.zeros(3) for _ in range(nr)]
        total, moment = ca.MX.zeros(3), ca.MX.zeros(3)
        for i, patch in enumerate(ref.contacts):
            f = force[3*i:3*i+3, k]
            location = x[:, k]+rm@anchors[i]
            normal = ca.DM([0., 0., 1.]) if patch.support_z is not None else rm@patch.inward
            fn = ca.dot(normal, f)
            if patch.active[k]:
                opt.subject_to(opt.bounded(0, fn, patch.force_limit))
                tangent = ca.DM(np.array([[1., 0.], [0., 1.], [0., 0.]])) if patch.support_z is not None else rm@patch.tangents
                ft = tangent.T@f
                # Conservative diamond inside the Coulomb cone. Linear faces
                # remain well conditioned at zero-force contact transitions.
                for sx, sy in ((1, 1), (1, -1), (-1, 1), (-1, -1)):
                    opt.subject_to(sx*ft[0]+sy*ft[1] <= patch.friction*fn)
                if patch.robot_index >= 0:
                    opt.subject_to((tips[:, patch.robot_index]-location)/.01 == 0)
                    world_hand[patch.robot_index] += f
                else:
                    initial_location = ref.initial_position+Rotation.from_quat(ref.initial_wxyz, scalar_first=True).apply(patch.center)
                    if abs(initial_location[2]-patch.support_z) > 1e-5 or patch.radius:
                        raise ValueError('Active support points must start on the fixed support plane')
                # Zero force at acquisition/release avoids interpolation of
                # contact force into an interval labelled inactive.
                if (k and not patch.active[k-1]) or (k < n-1 and not patch.active[k+1]):
                    opt.subject_to(f == 0)
            else:
                opt.subject_to(f == 0)
            if patch.robot_index >= 0:
                if not patch.active[k]:
                    # A hand may approach an underside patch from above and
                    # go around an edge. The infinite patch half-space would
                    # incorrectly rule that out before contact is active.
                    point = robot.kinematics(q[:, k], ref.base[k])[:, patch.robot_index]
                    delta = ca.fabs(rm.T@(point-x[:, k]))-ref.half_size
                    sdf = ca.sqrt(ca.sumsqr(ca.fmax(delta, 0))+1e-20)+ca.fmin(ca.mmax(delta), 0)
                    opt.subject_to(sdf >= robot.radius-2e-5)
            else:
                opt.subject_to(location[2]-patch.support_z >= -2e-5)
            total += f
            moment += ca.cross(rm@anchors[i], f)
            weight = (ref.times[min(k+1, n-1)]-ref.times[max(k-1, 0)])/2/duration
            reg += cfg.force_weight*weight*ca.sumsqr(f/patch.force_limit)
        if support_heights and not supported:
            for corner in corners:
                opt.subject_to((x[:, k]+rm@corner)[2] >= support_heights[0]-2e-5)
        wf = ca.horzcat(*world_hand)
        hand_force.append(wf)
        acceleration.append(total/ref.mass+ca.DM([0., 0., -9.81]))
        moments.append(moment)
        if supported:
            # The initially resting face sticks to the table. Balance its net
            # wrench, then let the integrated dynamics preserve the fixed pose
            # and zero velocity. Fixing pose at knots alone permits spurious
            # between-knot oscillation; adding redundant pose/velocity rows
            # on top of balance makes the NLP Jacobian singular.
            opt.subject_to(acceleration[-1] == 0)
            opt.subject_to(moment == 0)
        omega.append(rm@np.linalg.inv(ref.inertia)@rm.T@momentum[:, k])
        contact_tau = robot.force_torque(q[:, k], ref.base[k], wf)
        tau = robot.inverse_dynamics(q[:, k], v[:, k], a[:, k], ref.base[k])+contact_tau
        torque.append(tau)
        opt.subject_to(opt.bounded(-cfg.torque_margin*robot.caps, tau, cfg.torque_margin*robot.caps))
        if servo_kp is not None:
            offset = contact_tau/servo_kp
            servo_offsets.append(offset)
            opt.subject_to(opt.bounded(-servo_bound, offset, servo_bound))
            opt.subject_to(opt.bounded(robot.lower, q[:, k]+offset, robot.upper))
            if k:
                rate = (offset-servo_offsets[k-1])/(ref.times[k]-ref.times[k-1])
                opt.subject_to(opt.bounded(-cfg.servo_offset_rate, rate, cfg.servo_offset_rate))
        reg += (cfg.acceleration_weight*ca.sumsqr(a[:, k]/robot.acceleration)
                +cfg.torque_weight*ca.sumsqr(tau/robot.caps))/n
    for k, dt in enumerate(np.diff(ref.times)):
        # Joint integration is exact by the spline parameterization above.
        opt.subject_to((vel[:, k+1]-vel[:, k]-.5*dt*(acceleration[k]+acceleration[k+1])) == 0)
        opt.subject_to((x[:, k+1]-x[:, k]-.5*dt*(vel[:, k]+vel[:, k+1])-dt**2/12*(acceleration[k]-acceleration[k+1]))/.1 == 0)
        opt.subject_to((momentum[:, k+1]-momentum[:, k]-.5*dt*(moments[k]+moments[k+1]))/.1 == 0)
        opt.subject_to(quat[:, k+1]-quat_mul(rotation_quat(.5*dt*(omega[k]+omega[k+1])), quat[:, k]) == 0)
        reg += cfg.jerk_weight*dt/duration*ca.sumsqr((a[:, k+1]-a[:, k])/dt/40.)
        for i, patch in enumerate(ref.contacts):
            if patch.active[k] and patch.active[k+1]:
                reg += cfg.force_rate_weight*dt/duration*ca.sumsqr((force[3*i:3*i+3, k+1]-force[3*i:3*i+3, k])/dt/(patch.force_limit*5))
    data_object = 0
    position_scales = np.broadcast_to(np.asarray(ref.position_sigma), ref.observed_positions.shape)
    rotation_scales = np.broadcast_to(np.asarray(ref.rotation_sigma), ref.observed_positions.shape)
    for t, observed_p, observed_r, sigma_p, sigma_r in zip(ref.observation_times, ref.observed_positions, ref.observed_wxyz, position_scales, rotation_scales):
        k = min(np.searchsorted(ref.times, t, side='right')-1, n-2)
        dt = ref.times[k+1]-ref.times[k]; u = (t-ref.times[k])/dt
        xp = hermite(x[:, k], x[:, k+1], vel[:, k], vel[:, k+1], dt, u)
        # Normalized quaternion interpolation is used only for observation
        # evaluation. The knot dynamics use momentum and a Lie-group update.
        qr = (1-u)*quat[:, k]+u*quat[:, k+1]
        qr = qr/ca.sqrt(ca.dot(qr, qr)+1e-24)
        data_object += robust((xp-observed_p)/sigma_p)+robust(orientation_error(observed_r, qr)/sigma_r)
    data_object /= len(ref.observation_times)
    data_posture = cfg.posture_weight*robust((q-ref.joint_reference.T)/cfg.posture_sigma)/(n*robot.n)
    data_contact = sum(anchor_terms)/max(len(anchor_terms), 1)
    data_cost = data_object+data_posture+data_contact
    for cut in collision_cuts:
        time = cut.get('time', ref.times[cut.get('knot', 0)])
        k = min(np.searchsorted(ref.times, time, side='right')-1, n-2)
        dt = ref.times[k+1]-ref.times[k]; u = (time-ref.times[k])/dt
        cq = hermite(q[:, k], q[:, k+1], v[:, k], v[:, k+1], dt, u)
        cx = hermite(x[:, k], x[:, k+1], vel[:, k], vel[:, k+1], dt, u)
        d0 = .5*quat_mul(ca.vertcat(0, omega[k]), quat[:, k])
        d1 = .5*quat_mul(ca.vertcat(0, omega[k+1]), quat[:, k+1])
        cr = hermite(quat[:, k], quat[:, k+1], d0, d1, dt, u)
        cr = quat_rotation(cr/ca.sqrt(ca.dot(cr, cr)+1e-24))
        cb = np.zeros(25)
        cb[:3] = CubicSpline(ref.times, ref.base[:, :3])(time)
        cb[3:7] = RotationSpline(ref.times, Rotation.from_quat(ref.base[:, 3:7], scalar_first=True))(time).as_quat(scalar_first=True)
        def point(item):
            if item['kind'] == 'object':
                return cx+cr@item['local']
            if item['kind'] == 'world':
                return ca.DM(item['local'])
            return robot.point(cq, cb, item['body'], item['local'])
        opt.subject_to(ca.dot(ca.DM(cut['normal']), point(cut['b'])-point(cut['a'])) >= -2e-5)
    positions = np.column_stack([np.interp(ref.times, ref.observation_times, ref.observed_positions[:, j]) for j in range(3)])
    rotations = Slerp(ref.observation_times, Rotation.from_quat(ref.observed_wxyz, scalar_first=True))(ref.times).as_quat(scalar_first=True)
    if rotations[0]@ref.initial_wxyz < 0: rotations[0] *= -1
    for k in range(1, n):
        if rotations[k]@rotations[k-1] < 0: rotations[k] *= -1
    initial = dict(q=ref.joint_reference.T, v=np.zeros((robot.n, n)), a=np.zeros((robot.n, n)),
                   position=positions.T, velocity=np.zeros((3, n)), angular_momentum=np.zeros((3, n)),
                   wxyz=rotations.T, forces=np.zeros((3*nc, n)))
    for k in range(n):
        active = [i for i, c in enumerate(ref.contacts) if c.active[k]]
        for i in active:
            patch = ref.contacts[i]
            normal = np.array([0., 0., 1.]) if patch.support_z is not None else Rotation.from_quat(rotations[k], scalar_first=True).apply(patch.inward)
            initial['forces'][3*i:3*i+3, k] = np.array([0., 0., ref.mass*9.81/max(len(active), 1)])+(.0 if patch.support_z is not None else 3.)*normal
    variables = dict(q=q, v=v, a=a, position=x, velocity=vel, angular_momentum=momentum, wxyz=quat, forces=force)
    if warm_start:
        initial.update({key: np.asarray(warm_start[key]).T for key in variables if key in warm_start})
        if 'anchors' in warm_start:
            for i, variable in enumerate(uv):
                if variable is not None:
                    patch = ref.contacts[i]
                    opt.set_initial(variable, np.clip(patch.tangents.T@(warm_start['anchors'][i]-patch.center), -patch.radius, patch.radius))
    fit = np.vstack((basis(ref.times), basis(ref.times[0], 1), basis(ref.times[-1], 1)))
    values = np.vstack((initial['q'].T, initial['v'][:, 0], initial['v'][:, -1]))
    opt.set_initial(coefficients, np.linalg.solve(fit, values).T)
    for name, variable in variables.items():
        if name not in ('q', 'v', 'a'): opt.set_initial(variable, initial[name])
    options = dict(print_level=cfg.print_level, max_iter=cfg.max_iterations, max_cpu_time=cfg.max_seconds,
                   tol=cfg.tolerance, constr_viol_tol=cfg.tolerance, acceptable_tol=1e-5,
                   acceptable_constr_viol_tol=cfg.tolerance, hessian_approximation='exact' if cfg.exact_hessian else 'limited-memory',
                   fixed_variable_treatment='make_constraint', sb='yes')
    opt.solver('ipopt', {'print_time': False, 'expand': False}, options)
    opt.minimize(data_cost+cfg.data_stage_regularizer*reg)
    stages = []
    accepted_data = None
    first = None
    for stage in range(2 if cfg.lexicographic else 1):
        try:
            sol = opt.solve()
            success = True
        except RuntimeError:
            sol = opt.debug
            success = False
        stats = opt.stats()
        stage_info = dict(stage='data_fit' if stage == 0 else 'regularity', success=success,
                          status=stats.get('return_status', 'unknown'), iterations=stats.get('iter_count'),
                          data_cost=float(sol.value(data_cost)), regularity=float(sol.value(reg)))
        stages.append(stage_info)
        if not success:
            if first is not None:
                # Retain a genuinely solved first-stage trajectory if optional
                # regularization fails; never export a failed iterate as solved.
                return first | dict(stages=stages, seconds=perf_counter()-started,
                                    regularity_stage_succeeded=False)
            break
        if stage == 0:
            accepted_data = float(sol.value(data_cost))
            first = {name: np.asarray(sol.value(var)).T for name, var in variables.items()}
            first.update(anchors=np.asarray([np.asarray(sol.value(c)).ravel() for c in anchors]),
                         torque=np.asarray(sol.value(ca.horzcat(*torque))).T,
                         success=True, data_cost=accepted_data, data_fit_optimum=accepted_data,
                         data_object=float(sol.value(data_object)), data_posture=float(sol.value(data_posture)),
                         data_contact=float(sol.value(data_contact)), settings=asdict(cfg),
                         max_constraint_violation=_constraint_violation(opt, sol))
            first['success'] = first['max_constraint_violation'] < 1e-5
            if cfg.lexicographic:
                opt.set_initial(opt.x, sol.value(opt.x))
                opt.subject_to(data_cost <= accepted_data+cfg.data_allowance)
                opt.minimize(reg)
    result = {name: np.asarray(sol.value(var)).T for name, var in variables.items()}
    result.update(anchors=np.asarray([np.asarray(sol.value(c)).ravel() for c in anchors]),
                  torque=np.asarray(sol.value(ca.horzcat(*torque))).T,
                  success=success, stages=stages, seconds=perf_counter()-started,
                  data_cost=float(sol.value(data_cost)), data_fit_optimum=accepted_data,
                  data_object=float(sol.value(data_object)), data_posture=float(sol.value(data_posture)),
                  data_contact=float(sol.value(data_contact)), settings=asdict(cfg),
                  regularity_stage_succeeded=bool(success and cfg.lexicographic),
                  max_constraint_violation=_constraint_violation(opt, sol))
    result['success'] = bool(result['success'] and result['max_constraint_violation'] < 1e-5)
    return result


def _constraint_violation(opt, sol):
    values = np.asarray(sol.value(opt.g)).ravel()
    low, high = np.asarray(sol.value(opt.lbg)).ravel(), np.asarray(sol.value(opt.ubg)).ravel()
    return float(max(np.max(low-values), np.max(values-high), 0.))


def sample_solution(ref, result, times):
    """Sample the integrated trajectory; forces use linear, not cubic, interpolation."""
    t = np.asarray(times)
    qs = CubicHermiteSpline(ref.times, result['q'], result['v'])
    xs = CubicHermiteSpline(ref.times, result['position'], result['velocity'])
    def mul(a, b):
        return np.column_stack((a[:, 0]*b[:, 0]-np.sum(a[:, 1:]*b[:, 1:], axis=1),
                                a[:, :1]*b[:, 1:]+b[:, :1]*a[:, 1:]+np.cross(a[:, 1:], b[:, 1:])))
    rotation = Rotation.from_quat(result['wxyz'], scalar_first=True)
    matrices = rotation.as_matrix()
    inertia = matrices@ref.inertia@np.swapaxes(matrices, 1, 2)
    omega = np.linalg.solve(inertia, result['angular_momentum'][..., None])[..., 0]
    derivative = .5*mul(np.column_stack((np.zeros(len(omega)), omega)), result['wxyz'])
    spline = CubicHermiteSpline(ref.times, result['wxyz'], derivative)
    raw, raw_dot, raw_ddot = spline(t), spline(t, 1), spline(t, 2)
    norm = np.linalg.norm(raw, axis=1, keepdims=True)
    r = raw/norm
    norm_dot = np.sum(r*raw_dot, axis=1, keepdims=True)
    rdot = (raw_dot-r*norm_dot)/norm
    norm_ddot = np.sum(rdot*raw_dot+r*raw_ddot, axis=1, keepdims=True)
    rddot = (raw_ddot-2*rdot*norm_dot-r*norm_ddot)/norm
    conjugate = r*np.array([1, -1, -1, -1])
    world_omega = 2*mul(rdot, conjugate)[:, 1:]
    world_alpha = 2*mul(rddot, conjugate)[:, 1:]
    forces = np.column_stack([np.interp(t, ref.times, result['forces'][:, j]) for j in range(result['forces'].shape[1])])
    return dict(times=t, q=qs(t), v=qs(t, 1), a=qs(t, 2), jerk=qs(t, 3),
                position=xs(t), velocity=xs(t, 1), acceleration=xs(t, 2), wxyz=r,
                angular_velocity=world_omega, angular_acceleration=world_alpha,
                forces=forces.reshape(len(t), -1, 3))
